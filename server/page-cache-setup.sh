#!/usr/bin/env bash
# LiteSpeed Cache (no page cache on Apache) → WP Super Cache, configured by server/wpsc-configure.php.
# Run as the login user, from anywhere:  bash /var/www/html/wp-content/themes/yamaha-audio/server/page-cache-setup.sh
set -uo pipefail
W="${WP_PATH:-/var/www/html}"
WP="sudo -u www-data /usr/local/bin/wp --path=$W"
D="${DOMAIN:-yamaha-audio.ro}"
cd "$W"
echo "== plugins"
if $WP plugin is-active litespeed-cache 2>/dev/null; then
  $WP plugin deactivate litespeed-cache
fi
# LiteSpeed's drop-in must be gone before WP Super Cache can install its own
if [ -f "$W/wp-content/advanced-cache.php" ] && grep -qi litespeed "$W/wp-content/advanced-cache.php"; then
  sudo -u www-data rm -f "$W/wp-content/advanced-cache.php"
fi
if $WP plugin is-installed wp-super-cache 2>/dev/null; then
  $WP plugin activate wp-super-cache
else
  $WP plugin install wp-super-cache --activate
fi
echo "== configure"
$WP eval-file "$W/wp-content/themes/yamaha-audio/server/wpsc-configure.php"
$WP cache flush >/dev/null
echo "== warm + verify"
for i in 1 2 3; do curl -s -o /dev/null -w "home:     ttfb %{time_starttransfer}s\n" "https://$D/"; done
for i in 1 2; do curl -s -o /dev/null -w "category: ttfb %{time_starttransfer}s\n" "https://$D/categorie/receivere/"; done
for i in 1 2; do curl -s -o /dev/null -w "product:  ttfb %{time_starttransfer}s\n" "https://$D/produs/receiver-stereo-yamaha-r-n600a/"; done
curl -s "https://$D/" | tail -c 300 | grep -o 'Cached page generated by WP-Super-Cache[^>]*' || echo "no WP-Super-Cache footer comment yet (first hit builds it; run again)"
curl -sI "https://$D/" | grep -iE '^(HTTP|wp-super-cache|cache-control|content-encoding)'
echo "cart page must NOT be cached:"; curl -s "https://$D/cos/" | tail -c 300 | grep -c 'WP-Super-Cache' || true
echo "done"
